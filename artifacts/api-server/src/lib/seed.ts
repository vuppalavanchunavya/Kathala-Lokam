export async function seedKathalaLibrary(): Promise<void> {
  await db.insert(categoriesTable).values([...categories]).onConflictDoNothing();
  const existing = await db.select({ id: storiesTable.id }).from(storiesTable).limit(1);
  if (existing.length > 0) return;

  const categoryRows = await db.select().from(categoriesTable);
  const categoryIds = new Map(categoryRows.map((category) => [category.slug, category.id]));

  for (const story of stories) {
    const categoryId = categoryIds.get(story.category);
    if (!categoryId) throw new Error(`Missing category seed: ${story.category}`);
    const category = categories.find((item) => item.slug === story.category);
    if (!category) throw new Error(`Missing category metadata: ${story.category}`);
    const [insertedStory] = await db
      .insert(storiesTable)
      .values({
        slug: story.slug,
        title: story.title,
        categoryId,
        description: story.description,
        ageMin: story.ageMin,
        ageMax: story.ageMax,
        durationMinutes: story.durationMinutes,
        coverUrl: category.coverUrl,
        moral: story.moral,
        source: story.source,
        licence: "Original child-friendly text retelling; artwork and audio not included.",
        status: "published",
        featured: Boolean(story.featured),
        bedtime: Boolean(story.bedtime),
        keywords: story.keywords,
      })
      .returning();
    if (!insertedStory) continue;

    const translationItems = [
      {
        languageCode: "en",
        title: story.title,
        description: story.description,
        script: story.script,
        reviewed: true,
        status: "published",
      },
      ...(["te", "hi"] as const)
        .filter((languageCode) => story.translations?.[languageCode])
        .map((languageCode) => ({
          languageCode,
          title: story.translations?.[languageCode]?.title ?? story.title,
          description: story.description,
          script: story.translations?.[languageCode]?.script ?? story.script,
          reviewed: true,
          status: "published",
        })),
    ];

    for (const translation of translationItems) {
      const [insertedTranslation] = await db
        .insert(translationsTable)
        .values({ ...translation, storyId: insertedStory.id })
        .returning();
      if (!insertedTranslation) continue;
      const paragraphs = translation.script.split(/\n\n+/).filter(Boolean);
      if (paragraphs.length) {
        await db.insert(scenesTable).values(
          paragraphs.map((text, position) => ({
            translationId: insertedTranslation.id,
            position: position + 1,
            text,
            illustrationUrl: null,
            caption: null,
          })),
        );
      }
    }
  }
}
